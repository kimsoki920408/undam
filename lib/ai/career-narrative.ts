export function normalizeCareerSignals(source: CareerSignals): CareerSignals {
  const s = structuredClone(source);
  const luck = s.majorLuck;
  const timed = luck.available && ["exact", "approximate"].includes(luck.precision ?? "")
    && luck.startAge !== null && Number.isFinite(luck.startAge) && luck.startAge >= 0;
  if (!luck.available) luck.preview = [];
  if (!timed) {
    luck.startAge = null;
    luck.preview = luck.preview.map((value, index) => value.replace(/^\d+(?:\.\d+)?세\s*/, `${index + 1}번째 대운 `));
  }
  return s;
}

function basisFor(s: CareerSignals, ids: string[]) {
  return s.signals.filter(signal => ids.includes(signal.id)).map(signal => ({
    label: signal.label, value: signal.value,
    description: `${signal.source}. 해석 관점: ${signal.meaning}`,
  }));
}

